<#
 winusb-bind.ps1 -- bind ONE USB device to Windows' own WinUSB driver, by its VID and PID, so that
 symbioticd can open it (a USBTMC instrument taken off its vendor driver). Run as Administrator.

   .\winusb-bind.ps1 -VidPid F4EC:1103
   .\winusb-bind.ps1 -VidPid F4EC:1103 -Name 'My instrument'
   .\winusb-unbind.ps1 -VidPid F4EC:1103                  # and back

 What it does, using only what ships with Windows (no WDK, no Zadig, nothing downloaded):
   * writes an INF that matches this one hardware ID, USB\VID_xxxx&PID_yyyy. A hardware-ID match
     outranks a vendor USBTMC driver's match on the device class, so this device -- and only this
     VID/PID -- moves to WinUSB; every other instrument stays where it is.
   * signs its catalog with a self-signed certificate: the driver store wants a signature this
     machine trusts, though the package has no kernel code of its own (WinUSB.sys is Microsoft's).
     One named 'Symbiotic device driver' is made the first time and reused after that, so no
     second one is added to LocalMachine\Root. Know what that is: its private key is in your
     user's certificate store, and the whole machine trusts it as a root.
   * adds the package to the driver store and installs it on the device.

 Afterwards the vendor's software and every other VISA lose this device until winusb-unbind.ps1
 removes the package, when Windows gives it back to the vendor driver (still in the store).
#>
param(
    [Parameter(Mandatory)][ValidatePattern('^[0-9A-Fa-f]{4}:[0-9A-Fa-f]{4}$')][string]$VidPid,
    [string]$Name = 'USB instrument'
)
$ErrorActionPreference = 'Stop'

if (-not ([Security.Principal.WindowsPrincipal] [Security.Principal.WindowsIdentity]::GetCurrent()
    ).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
    throw "Administrator rights are required. Run this from an elevated PowerShell."
}

$vid, $prod = $VidPid.ToUpper().Split(':')
$hwid = "USB\VID_$vid&PID_$prod"
$base = "symbiotic_winusb_$($vid.ToLower())_$($prod.ToLower())"

function Show-Device {
    # Exactly this VID/PID (the device itself, and its interfaces if it is a composite).
    $d = @(Get-PnpDevice -PresentOnly | Where-Object { $_.InstanceId -like "$hwid\*" -or $_.InstanceId -like "$hwid&*" })
    if (-not $d) { Write-Host "  (not plugged in)"; return $d }
    $d | ForEach-Object { Write-Host ("  {0}  {1}  service={2}  status={3}" -f $_.InstanceId, $_.FriendlyName, $_.Service, $_.Status) }
    $d
}

Write-Host "Now:"
$now = Show-Device
if ($now | Where-Object { $_.InstanceId -like "$hwid&MI_*" }) {
    # A composite device: binding the whole of it would take its other functions away too. Not supported.
    throw "$hwid is a composite device; binding one of its interfaces is not supported by this script."
}

Write-Host "1/4 A certificate to sign with"
# One the machine already trusts goes first: there can be more than one with the same name, and taking an untrusted one
# would add a second root after all.
$roots = @(Get-ChildItem Cert:\LocalMachine\Root | ForEach-Object Thumbprint)
$cert = Get-ChildItem Cert:\CurrentUser\My |
    Where-Object { $_.Subject -eq 'CN=Symbiotic device driver' -and $_.HasPrivateKey -and $_.NotAfter -gt (Get-Date) } |
    Sort-Object { $_.Thumbprint -notin $roots } | Select-Object -First 1
if ($cert) {
    Write-Host "  reusing '$($cert.Subject)' ($($cert.Thumbprint))"
} else {
    $cert = New-SelfSignedCertificate -Type CodeSigningCert -Subject 'CN=Symbiotic device driver' `
            -CertStoreLocation Cert:\CurrentUser\My -NotAfter (Get-Date).AddYears(5)
    Write-Host "  made 'CN=Symbiotic device driver' ($($cert.Thumbprint))"
}
# Trusted for chain validation (Root) and for a silent install (TrustedPublisher); already there
# for a reused one, and not imported twice.
$work = Join-Path $env:TEMP $base
New-Item -ItemType Directory -Force $work | Out-Null
$cer = Join-Path $work 'signer.cer'
Export-Certificate -Cert $cert -FilePath $cer | Out-Null
foreach ($store in 'Root', 'TrustedPublisher') {
    if (-not (Get-ChildItem "Cert:\LocalMachine\$store" | Where-Object Thumbprint -eq $cert.Thumbprint)) {
        Import-Certificate -FilePath $cer -CertStoreLocation "Cert:\LocalMachine\$store" | Out-Null
        Write-Host "  trusted in LocalMachine\$store"
    }
}

Write-Host "2/4 The INF, for $hwid only"
$inf = Join-Path $work "$base.inf"
$date = (Get-Date).ToString('MM/dd/yyyy')
@"
; Bind $hwid ($Name) to the in-box WinUSB driver, for Symbiotic's symbioticd.
; Generated by winusb-bind.ps1. No kernel binary of its own: it includes winusb.inf.
; To remove: winusb-unbind.ps1 -VidPid $vid`:$prod

[Version]
Signature   = "`$Windows NT`$"
Class       = USBDevice
ClassGuid   = {88BAE032-5A81-49f0-BC3D-A4FF138216D6}
Provider    = %Provider%
CatalogFile = $base.cat
DriverVer   = $date,1.0.0.0
PnpLockdown = 1

[Manufacturer]
%Provider% = Devices, NTamd64

[Devices.NTamd64]
%DeviceName% = USB_Install, $hwid

[USB_Install]
Include = winusb.inf
Needs   = WINUSB.NT

[USB_Install.Services]
Include = winusb.inf
Needs   = WINUSB.NT.Services

[USB_Install.HW]
AddReg = Dev_AddReg

[Dev_AddReg]
; The device interface a WinUSB client opens it through; one GUID for every device Symbiotic binds.
HKR,,DeviceInterfaceGUIDs,0x10000,"{64F9CE3B-42E2-489B-AED7-DEE3AD038EC4}"

[Strings]
Provider   = "Symbiotic"
DeviceName = "$Name (WinUSB, Symbiotic)"
"@ | Set-Content -Path $inf -Encoding ASCII

Write-Host "3/4 Its catalog, signed"
$cat = Join-Path $work "$base.cat"
Remove-Item $cat -ErrorAction SilentlyContinue
# The INF alone, not the directory: a directory catalog hashes whatever else is in it.
New-FileCatalog -Path $inf -CatalogFilePath $cat -CatalogVersion 2 | Out-Null
$sig = Set-AuthenticodeSignature -FilePath $cat -Certificate $cert
if ($sig.Status -ne 'Valid') { throw "Signing the catalog failed: $($sig.Status)" }

Write-Host "4/4 Into the driver store, and onto the device"
pnputil /add-driver $inf /install
Start-Sleep 3
pnputil /scan-devices | Out-Null
Start-Sleep 3

Write-Host "Now:"
$after = Show-Device
if ($after | Where-Object Service -eq 'WINUSB') {
    Write-Host "Bound to WinUSB. symbioticd can open it; the vendor driver no longer serves it."
} elseif ($after) {
    Write-Warning "The package is in the driver store but the device is not on WinUSB yet. Unplug it and plug it back in; if that does not do it, see Device Manager."
} else {
    Write-Host "The package is in the driver store; the device binds to WinUSB when it is plugged in."
}
