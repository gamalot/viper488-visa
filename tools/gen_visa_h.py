# The names already defined in visatype.h.
SKIP = {"VI_NULL", "VI_TRUE", "VI_FALSE"}


def value(name, v):
    status = name.startswith(("VI_SUCCESS", "VI_WARN", "VI_ERROR"))
    if status:
        if v < 0:
            return "(_VI_ERROR+0x%08XL)" % (v + 0x80000000)
        return "(0x%08XL)" % v if v else "(0L)"
    if v < 0:
        return "(%d)" % v
    if v > 0x7FFFFFFF:
        return "(0x%08XUL)" % v
    if v > 0xFFFF:
        return "(0x%08XUL)" % v
    return "(%d)" % v


def main():
    src = inspect.getsource(c)
    names = []
    for m in re.finditer(r"^(VI_[A-Z0-9_]+)\s*(?::[^=]*)?=", src, re.M):
        n = m.group(1)
        if n not in names and n not in SKIP and isinstance(getattr(c, n, None), int):
            names.append(n)
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "visatype.h"), "w", newline="\n") as f:
        f.write(VISATYPE)
    with open(os.path.join(OUT, "visa.h"), "w", newline="\n") as f:
        f.write(HEAD)
        for n in names:
            f.write("#define %-40s %s\n" % (n, value(n, int(getattr(c, n)))))
        f.write(TAIL)
    print("%d constants, pyvisa %s" % (len(names), getattr(__import__("pyvisa"), "__version__", "?")))


main()
