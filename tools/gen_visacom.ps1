<#
 gen_visacom.ps1 -- generate dotnet/Symbiotic.VisaCom/Generated.cs from the VISA COM interop assembly's metadata.
 Run with Windows PowerShell 5.1 (it loads the .NET Framework assembly by reflection):

   powershell -NoProfile -ExecutionPolicy Bypass -File tools\gen_visacom.ps1 [-Pia <Ivi.Visa.Interop.dll>] [-Out <Generated.cs>]

 Why: VISA COM returns completion codes as success HRESULTs
 (VI_SUCCESS_MAX_CNT tells a reader there is more), which a C# class implementing the interop assembly's
 interfaces cannot return. So every interface gets a [PreserveSig] twin with the same IID and the same vtable
 order -- the metadata order of the interop assembly's own declarations -- and each COM class lists the twins
 before the interop interfaces, so COM callers get the twins' vtables. The twins forward to the class's
 interop-style members and turn what they throw into HRESULTs.
#>
param(
    [string]$Pia = (Join-Path $env:ProgramFiles 'IVI Foundation\VISA\VisaCom64\Primary Interop Assemblies\Ivi.Visa.Interop.dll'),
    [string]$Out = (Join-Path $PSScriptRoot '..\dotnet\Symbiotic.VisaCom\Generated.cs')
)
$ErrorActionPreference = 'Stop'
$asm = [Reflection.Assembly]::LoadFrom($Pia)
$ns = 'Ivi.Visa.Interop'

# The COM classes and the interfaces each has, in the order COM should see them.
$classes = [ordered]@{
    ResourceManager = @('IResourceManager3', 'IResourceManager')
    GpibInstr   = @('IVisaSession', 'IEventManager', 'IBaseMessage', 'IMessage', 'IAsyncMessage', 'IGpib')
    GpibIntfc   = @('IVisaSession', 'IEventManager', 'IGpibIntfc', 'IGpibIntfcMessage')
    TcpipInstr  = @('IVisaSession', 'IEventManager', 'IBaseMessage', 'IMessage', 'IAsyncMessage', 'ITcpipInstr', 'ITcpipInstr2', 'IHislipInstr', 'IHislipInstr2')
    TcpipSocket = @('IVisaSession', 'IEventManager', 'IBaseMessage', 'IMessage', 'IAsyncMessage', 'ITcpipSocket', 'ITcpipSocket2')
    UsbInstr    = @('IVisaSession', 'IEventManager', 'IBaseMessage', 'IMessage', 'IAsyncMessage', 'IUsb')
    AsrlInstr   = @('IVisaSession', 'IEventManager', 'IBaseMessage', 'IMessage', 'IAsyncMessage', 'ISerial')
}
# Members that clash by signature with another interface's and so are renamed in the classes.
$renamed = @{ 'IAsyncMessage.Read' = 'AsyncRead'; 'IAsyncMessage.Write' = 'AsyncWrite'; 'IAsyncMessage.WriteString' = 'AsyncWriteString' }
# Interfaces a method hands back that must reach COM as the twin's pointer, not a vtable of the interop type.
$sessionReturns = @('IVisaSession')

function TypeName([Type]$t) {
    if ($t.IsByRef) { $t = $t.GetElementType() }
    if ($t.IsArray) { return (TypeName $t.GetElementType()) + '[]' }
    switch ($t.FullName) {
        'System.Int32' { return 'int' }   'System.Int16' { return 'short' } 'System.Byte' { return 'byte' }
        'System.Boolean' { return 'bool' } 'System.String' { return 'string' } 'System.Object' { return 'object' }
        'System.Double' { return 'double' } 'System.Single' { return 'float' } 'System.Int64' { return 'long' }
        'System.IntPtr' { return 'System.IntPtr' } 'System.Void' { return 'void' }
    }
    if ($t.Namespace -eq $ns) { return "global::$ns.$($t.Name)" }
    return "global::$($t.FullName)"
}

function Marshal([Reflection.ParameterInfo]$p) {
    $m = $p.GetCustomAttributes([Runtime.InteropServices.MarshalAsAttribute], $false)
    if (-not $m) { return '' }
    $m = $m[0]
    $s = "MarshalAs(UnmanagedType.$($m.Value)"
    if ($m.Value -eq [Runtime.InteropServices.UnmanagedType]::SafeArray) { $s += ", SafeArraySubType = VarEnum.$($m.SafeArraySubType)" }
    return $s + ')'
}

function Attrs([Reflection.ParameterInfo]$p) {
    $a = @()
    if ($p.IsIn) { $a += 'In' }
    if ($p.IsOut -and $p.ParameterType.IsByRef -and $p.IsIn) { $a += 'Out' }
    $m = Marshal $p
    if ($m) { $a += $m }
    if ($a.Count) { return '[' + ($a -join ', ') + '] ' }
    return ''
}

function Methods([Type]$t) { $t.GetMethods() | Sort-Object MetadataToken }

$sb = New-Object Text.StringBuilder
function W([string]$s) { [void]$sb.AppendLine($s) }

W '// <auto-generated> by tools/gen_visacom.ps1 from Ivi.Visa.Interop''s metadata: do not edit.'
W '// The [PreserveSig] twins of the VISA COM interfaces (same IIDs, same vtable order) and, for each COM class,'
W '// its interface list (twins first) and the twins'' forwarding.'
W 'using System;'
W 'using System.ComponentModel;'
W 'using System.Runtime.InteropServices;'
W ''
W 'namespace Symbiotic.VisaCom.Twins'
W '{'
$needed = $classes.Values | ForEach-Object { $_ } | Select-Object -Unique
foreach ($name in $needed) {
    $t = $asm.GetType("$ns.$name", $true)
    $guid = $t.GUID.ToString().ToUpperInvariant()
    W "    [ComImport, ComVisible(true), Guid(""$guid""), InterfaceType(ComInterfaceType.InterfaceIsIUnknown), EditorBrowsable(EditorBrowsableState.Never)]"
    W "    public interface ${name}Twin"
    W '    {'
    foreach ($m in Methods $t) {
        $ps = @($m.GetParameters() | ForEach-Object {
            $dir = if ($_.ParameterType.IsByRef) { if ($_.IsOut -and -not $_.IsIn) { 'out ' } else { 'ref ' } } else { '' }
            "$(Attrs $_)$dir$(TypeName $_.ParameterType) $($_.Name)"
        })
        $ret = $m.ReturnType
        if ($ret -ne [void]) {
            if ($sessionReturns -contains $ret.Name) { $ps += 'out System.IntPtr ret' }
            else {
                $rm = Marshal $m.ReturnParameter
                $ps += $(if ($rm) { "[$rm] " } else { '' }) + "out $(TypeName $ret) ret"
            }
        }
        W "        [PreserveSig] int $($m.Name)($($ps -join ', '));"
    }
    W '    }'
    W ''
}
W '}'
W ''
W 'namespace Symbiotic.VisaCom'
W '{'
W '    using Symbiotic.VisaCom.Twins;'
W ''
foreach ($cls in $classes.Keys) {
    $ifs = $classes[$cls]
    $list = @($ifs | ForEach-Object { "${_}Twin" }) + @($ifs | ForEach-Object { "global::$ns.$_" })
    W "    partial class $cls :"
    W ('        ' + ($list -join ",`r`n        "))
    W '    {'
    foreach ($name in $ifs) {
        $t = $asm.GetType("$ns.$name", $true)
        foreach ($m in Methods $t) {
            $params = @($m.GetParameters())
            $decl = @($params | ForEach-Object {
                $dir = if ($_.ParameterType.IsByRef) { if ($_.IsOut -and -not $_.IsIn) { 'out ' } else { 'ref ' } } else { '' }
                "$dir$(TypeName $_.ParameterType) $($_.Name)"
            })
            $argList = @($params | ForEach-Object {
                $dir = if ($_.ParameterType.IsByRef) { if ($_.IsOut -and -not $_.IsIn) { 'out ' } else { 'ref ' } } else { '' }
                "$dir$($_.Name)"
            })
            $pia = "((global::$ns.$name)this)"
            $ret = $m.ReturnType
            $isSession = $ret -ne [void] -and $sessionReturns -contains $ret.Name
            if ($ret -ne [void]) { $decl += $(if ($isSession) { 'out System.IntPtr ret' } else { "out $(TypeName $ret) ret" }) }
            if ($m.Name -like 'get_*') { $call = "$pia.$($m.Name.Substring(4))" }
            elseif ($m.Name -like 'set_*') { $call = "$pia.$($m.Name.Substring(4)) = $($params[-1].Name)" }
            else { $call = "$pia.$($m.Name)($($argList -join ', '))" }
            if ($ret -eq [void]) { $body = "$call;" }
            elseif ($isSession) { $body = "ret = ComObjects.Pointer($call, typeof(IVisaSessionTwin).GUID);" }
            else { $body = "ret = $call;" }
            $init = @($params | Where-Object { $_.ParameterType.IsByRef -and $_.IsOut -and -not $_.IsIn } | ForEach-Object { "$($_.Name) = default;" })
            if ($ret -ne [void]) { $init += 'ret = default;' }
            W "        int ${name}Twin.$($m.Name)($($decl -join ', '))"
            W "        {"
            if ($init) { W "            $($init -join ' ')" }
            W "            Begin();"
            W "            try { $body return End(); }"
            W "            catch (Exception e) { return Fail(e); }"
            W "        }"
        }
        # The interop members this class implements under another name.
        foreach ($m in Methods $t) {
            $key = "$name.$($m.Name)"
            if (-not $renamed.ContainsKey($key)) { continue }
            $params = @($m.GetParameters())
            $decl = @($params | ForEach-Object { $(if ($_.ParameterType.IsByRef) { 'ref ' } else { '' }) + "$(TypeName $_.ParameterType) $($_.Name)" })
            $argList = @($params | ForEach-Object { $(if ($_.ParameterType.IsByRef) { 'ref ' } else { '' }) + $_.Name })
            W "        $(TypeName $m.ReturnType) global::$ns.$name.$($m.Name)($($decl -join ', ')) => $($renamed[$key])($($argList -join ', '));"
        }
    }
    W '    }'
    W ''
}
W '}'
$text = $sb.ToString() -replace "`r?`n", "`n"
[IO.File]::WriteAllText([IO.Path]::GetFullPath($Out), $text, (New-Object Text.UTF8Encoding($false)))
"wrote $Out"
