#!/usr/bin/env python3
"""gen_visacom_attrs.py -- the VISA attributes' C types, for VISA COM's GetAttribute/SetAttribute (VARIANT),
and for viFindRsrc's attribute expressions (which must refuse a local attribute, VPP-4.3 RULE 4.4.7).

    python3 tools/gen_visacom_attrs.py > dotnet/Symbiotic.VisaCom/AttributeTypes.cs
    python3 tools/gen_visacom_attrs.py rust > crates/symbiotic-core/src/attrs.rs

From pyvisa's attribute table, as include/visa.h's constants are (tools/gen_visa_h.py): a VARIANT needs the
attribute's width and signedness, which the C API leaves to the caller.
"""
import pyvisa
import pyvisa.attributes as a

KIND = {
    "ViInt16": "I16", "ViUInt16": "U16", "ViUInt32": "U32", "ViInt32": "I32", "ViBoolean": "Bool", "ViBool": "Bool",
    "ViString": "Str", "ViRsrc": "Str", "ViUInt8": "U8", "ViVersion": "U32", "ViAccessMode": "U32", "ViStatus": "I32",
    "ViJobId": "U32", "ViSession": "U32", "ViUInt64": "U64", "ViBusAddress64": "U64", "ViBusSize64": "U64", "ViBuf": "Ptr",
}
import sys

# pyvisa keeps the IDs with the top bit set (0xBFFF....) as negative ints.
ATTRS = sorted((k & 0xFFFFFFFF, v) for k, v in a.AttributesByID.items())

if sys.argv[1:] == ["rust"]:
    print("//! Generated by tools/gen_visacom_attrs.py from pyvisa %s's attribute table: do not edit." % pyvisa.__version__)
    print("//! Every VISA attribute's name, id, C type and whether it is local to a session (a global one is the")
    print("//! resource's): what a viFindRsrc attribute expression may name (resource.rs).")
    print()
    print("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
    print("pub enum Kind {")
    print("    U8,")
    print("    I16,")
    print("    U16,")
    print("    I32,")
    print("    U32,")
    print("    U64,")
    print("    Bool,")
    print("    Str,")
    print("    Ptr,")
    print("}")
    print()
    print("/// (name, id, kind, local)")
    print("pub const ATTRS: &[(&str, u32, Kind, bool)] = &[")
    for aid, attr in ATTRS:
        print('    ("%s", 0x%08X, Kind::%s, %s),' % (attr.visa_name, aid, KIND[attr.visa_type], "true" if attr.local else "false"))
    print("];")
    print()
    print("/// The attribute called `name` (as visa.h spells it).")
    print("pub fn by_name(name: &str) -> Option<(u32, Kind, bool)> {")
    print("    ATTRS.iter().find(|a| a.0 == name).map(|a| (a.1, a.2, a.3))")
    print("}")
    sys.exit(0)

print("// <auto-generated> by tools/gen_visacom_attrs.py from pyvisa %s's attribute table: do not edit." % pyvisa.__version__)
print("using System.Collections.Generic;")
print()
print("namespace Symbiotic.VisaCom")
print("{")
print("    internal enum AttrKind { U8, I16, U16, I32, U32, U64, Bool, Str, Ptr }")
print()
print("    internal static class AttributeTypes")
print("    {")
print("        public static readonly Dictionary<uint, AttrKind> Kinds = new Dictionary<uint, AttrKind>")
print("        {")
for aid, attr in ATTRS:
    print("            { 0x%08X, AttrKind.%s }, // %s" % (aid, KIND[attr.visa_type], attr.visa_name))
print("        };")
print("    }")
print("}")
